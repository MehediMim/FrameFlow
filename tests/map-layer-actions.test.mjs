import assert from 'node:assert/strict';
import { newMapProject, makeAction, makeShot, validateMapProject } from '../map-engine.mjs';
import { duplicateLayers, removeLayers } from '../map-layer-actions.mjs';
import { makeObjectGroup } from '../map-object-groups.mjs';
const p=newMapProject();p.actions=[makeAction('object',15,{id:'a'}),makeAction('object',25,{id:'b'}),makeAction('pin',10,{id:'pin'})];
const group=makeObjectGroup(p,['a','b'],()=>({lon:0,lat:0}),'group');
p.shots=[makeShot('keyframed',0,{id:'camera',fullTimelineCamera:true}),makeShot('followPlane',0,{id:'follow',planeId:'a'})];
const snapshot=structuredClone(p);let serial=0;
const copies=duplicateLayers(p,['group','a','pin','camera'],()=>`copy-${++serial}`);
assert.equal(copies.length,2,'selected children are not duplicated twice; permanent camera is protected');
const duplicate=p.actions.find(a=>a.id===copies[0]);
assert.equal(duplicate.type,'group');assert.equal(duplicate.memberIds.length,2);
assert.deepEqual(duplicate.memberIds.map(id=>p.actions.find(a=>a.id===id).start),[15,25],'group copy preserves every member start');
assert.deepEqual(p.actions.find(a=>a.id===copies[1]).place,snapshot.actions.find(a=>a.id==='pin').place,'duplicate preserves its map location');
removeLayers(p,['group','camera']);
assert.ok(p.shots.some(s=>s.id==='camera'),'permanent camera cannot be deleted');
assert.ok(!p.actions.some(a=>['group','a','b'].includes(a.id)),'deleting a group removes its own children');
assert.equal(p.shots.find(s=>s.id==='follow').planeId,'','deleted route references are cleared');
assert.ok(duplicate.memberIds.every(id=>p.actions.some(a=>a.id===id)),'other group copies remain intact');
validateMapProject(JSON.parse(JSON.stringify(p)));
const full=newMapProject();full.actions=Array.from({length:200},()=>makeAction('pin',0));const before=structuredClone(full);
assert.throws(()=>duplicateLayers(full,[full.actions[0].id]),/200/);assert.deepEqual(full,before,'failed duplication is atomic');
console.log('Shared layer actions: mixed copies, persistent groups, original timing/location, camera protection, limits and deletion cleanup passed');
