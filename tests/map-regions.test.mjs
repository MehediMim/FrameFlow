import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {combinedFeature,borderSection,nearestBorderPosition,detailCountriesOf} from '../map-regions.mjs';
import * as E from '../map-engine.mjs';
const ring=coords=>({xy:new Float64Array(coords.flat()),n:coords.length,area:1,hole:false});
const a={name:'Left',rings:[ring([[0,0],[1,0],[1,1],[0,1],[0,0]])],bbox:[0,0,1,1],cx:.5,cy:.5};
const b={...a,name:'Right',rings:[ring([[1,0],[2,0],[2,1],[1,1],[1,0]])],bbox:[1,0,2,1],cx:1.5};
const joined=combinedFeature([a,b]);
assert.equal(joined.rings.length,1,'adjacent regions become one outline');
assert.equal(joined.rings[0].n,7,'shared boundary is removed');
assert.deepEqual(joined.bbox,[0,0,2,1]);
const length=r=>{let n=0;for(let i=1;i<r.n;i++)n+=Math.hypot(r.xy[i*2]-r.xy[i*2-2],r.xy[i*2+1]-r.xy[i*2-1]);return n};
assert.equal(length(borderSection(a.rings[0],0,.5)),2);
assert.equal(length(borderSection(a.rings[0],.75,.25)),2,'wrap around outline');
assert.equal(length(borderSection(a.rings[0],0,1,1,true)),4,'reverse full outline');
assert.equal(length(borderSection(a.rings[0],0,.5,.5)),1,'animation reveals segment progressively');
assert.equal(length(borderSection(a.rings[0],.2,.2)),0,'same endpoints mean no segment');
assert.equal(nearestBorderPosition(a,1,.5).position,.375);
assert.deepEqual(detailCountriesOf({mode:'world',detailCountries:['Bangladesh','Myanmar','Bangladesh']}),['Bangladesh','Myanmar']);
const load=name=>JSON.parse(readFileSync(new URL('../map-data/'+name,import.meta.url),'utf8'));
const geo=E.buildGeo(load('countries-50m.json'),load('countries-110m.json'));
for(const country of ['bangladesh','myanmar'])E.installCountryDetail(geo,load(country+'-detail.json'));
const p=E.newMapProject();p.area={mode:'world',detailCountries:['Bangladesh','Myanmar'],detailLevels:{Bangladesh:'district',Myanmar:'division'}};
assert.equal(E.detailRegions(p,geo).length,79,'world supports per-country detail levels');
const target={kind:'regions',name:'Two countries',members:[{kind:'country',name:'Bangladesh'},{kind:'country',name:'Myanmar'}]};
p.actions=[E.makeAction('border',0,{target,borderPartial:true,borderFrom:20,borderTo:60,borderReverse:true}),E.makeAction('highlight',0,{target})];
E.validateMapProject(JSON.parse(JSON.stringify(p)));
assert.ok(E.lonLatOf(geo,target),'combined targets can be camera destinations');
const bad=structuredClone(p);bad.actions[0].target.members=[{kind:'regions',name:'Nested',members:target.members}];
assert.throws(()=>E.validateMapProject(bad),/border target/);
const badEndpoint=structuredClone(p);badEndpoint.actions[0].borderTo=101;
assert.throws(()=>E.validateMapProject(badEndpoint),/endpoint/);
console.log('Multi-region outlines, world country details, border endpoints and project validation passed');
