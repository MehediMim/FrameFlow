import { poseAt, easings } from './engine.mjs?v=sparse-blur-1';

// Fit smooth segments to within a third of a blur pixel instead of baking every frame.
const tolerance=1/3;
function compact(samples) {
 const result=[];
 function fit(first,last){
  const a=samples[first],b=samples[last];
  let best={error:Infinity};
  for(const e of ['linear','easeSine','easeInOut','easeIn','easeOut']){
   let error=0,split=first;
   for(let i=first+1;i<last;i++){
    const expected=a.v+(b.v-a.v)*easings[e]((samples[i].f-a.f)/(b.f-a.f));
    const delta=Math.abs(expected-samples[i].v);
    if(delta>error){error=delta;split=i}
   }
   if(error<best.error)best={error,split,e};
  }
  if(best.error>tolerance){fit(first,best.split);fit(best.split,last)}
  else result.push({...a,e:best.e});
 }
 // Keep turning points and the edges of holds exactly timed.
 let first=0;
 for(let i=1;i<samples.length-1;i++){
  const before=Math.sign(samples[i].v-samples[i-1].v),after=Math.sign(samples[i+1].v-samples[i].v);
  if(before!==after){fit(first,i);first=i}
 }
 if(first<samples.length-1)fit(first,samples.length-1);
 result.push({...samples.at(-1)});
 return result;
}

// Also repair consecutive linear keys generated by the earlier frame-by-frame migration.
function compactBakedKeys(keys){
 const result=[];
 for(let i=0;i<keys.length;){
  let end=i;
  while(end+1<keys.length&&keys[end].e==='linear'&&keys[end+1].f===keys[end].f+1)end++;
  const run=keys.slice(i,end+1);
  result.push(...(run.length>=8?compact(run):run));
  i=end+1;
 }
 return result;
}

export function migrateBlurClips(project) {
 let migrated=false;
 for(const layer of project.layers){
  const clips=(layer.fxClips||[]).filter(fx=>fx.kind==='blur'||fx.name==='blur');
  if(!clips.length){
   const keys=layer.keys.blur||[],reduced=compactBakedKeys(keys);
   if(reduced.length<keys.length){layer.keys.blur=reduced;migrated=true}
   continue;
  }
  const source={...layer,fxClips:clips},keys=[];
  for(let f=0;f<project.frames;f++){
   const key={f,v:poseAt(source,f).blur||0,e:'linear'};
   keys.push(key);
  }
  layer.keys.blur=compact(keys);
  layer.fxClips=layer.fxClips.filter(fx=>!clips.includes(fx));
  migrated=true;
 }
 return migrated;
}
