import assert from 'node:assert/strict';
import { newMapProject, makeShot, cameraAt, validateMapProject, lonToX, latToY, actionProgress } from '../map-engine.mjs';
import { retimeMapItem, setAnimationKey } from '../map-timing.mjs';
import { cameraPoseAt, cameraKeysOf, putCameraKey, removeCameraKey, moveCameraKey } from '../map-camera.mjs';

const emptyCamera = makeShot('keyframed', 0);
assert.deepEqual(cameraKeysOf(emptyCamera), [], 'new camera has no default keyframes');
assert.deepEqual(cameraPoseAt(emptyCamera, 0), cameraPoseAt(emptyCamera, 50), 'unkeyed camera holds its initial view');
putCameraKey(emptyCamera, 20, { zoom: 4 });
assert.equal(cameraKeysOf(emptyCamera).length, 1, 'first edit adds only the requested key');
removeCameraKey(emptyCamera, 20, ['zoom']);
assert.deepEqual(cameraKeysOf(emptyCamera), [], 'removing the last key does not recreate endpoints');

const p = newMapProject();
const a = { lon: -20, lat: 10, zoom: 2, pitch: 0, bearing: -45 };
const b = { lon: 40, lat: 50, zoom: 6, pitch: 60, bearing: 90 };
p.shots = [makeShot('keyframed', 10, { dur: 80, easing: 'linear', cameraFrom: a, cameraTo: b, cameraKeys: undefined })];
validateMapProject(JSON.parse(JSON.stringify(p)));
const multi = makeShot('keyframed', 10, { dur: 100, easing: 'linear', cameraFrom: a, cameraTo: b, cameraKeys: undefined });
putCameraKey(multi, 50, { zoom: 9 });
putCameraKey(multi, 70, { pitch: 20, bearing: 180 });
assert.equal(cameraKeysOf(multi).length, 4);
assert.equal(cameraPoseAt(multi, 50).zoom, 9);
assert.equal(cameraPoseAt(multi, 30).zoom, 5.5);
assert.equal(cameraPoseAt(multi, 50).lon, 4, 'zoom key leaves position on its independent track');
assert.equal(cameraPoseAt(multi, 70).pitch, 20);
assert.equal(cameraPoseAt(multi, 70).bearing, 180);
moveCameraKey(multi, 70, 80, ['pitch']);
assert.equal(cameraKeysOf(multi).find(k => k.frame === 70).values.pitch, undefined);
assert.equal(cameraKeysOf(multi).find(k => k.frame === 70).values.bearing, 180);
assert.equal(cameraPoseAt(multi, 80).pitch, 20);
removeCameraKey(multi, 50, ['zoom']);
assert.equal(cameraKeysOf(multi).some(k => k.frame === 50), false);
retimeMapItem(multi, 30, 100);
assert.equal(cameraPoseAt(multi, 100).pitch, 20, 'clip moves shift camera keys');
const multiProject = newMapProject(); multiProject.shots = [multi];
validateMapProject(JSON.parse(JSON.stringify(multiProject)));
multi.cameraKeys[0].values.zoom = Infinity;
assert.throws(() => validateMapProject(multiProject), /camera keyframe property/);
const start = cameraAt(p, {}, 1280, 720, 10), mid = cameraAt(p, {}, 1280, 720, 50), end = cameraAt(p, {}, 1280, 720, 90);
assert.equal(start.cx, lonToX(a.lon));
assert.equal(start.cy, latToY(a.lat));
for (const k of ['cx', 'cy', 'zoom', 'pitch', 'bearing']) assert.ok(Math.abs(mid[k] - (start[k] + end[k]) / 2) < 1e-10, `${k} interpolates`);
assert.equal(end.zoom, b.zoom);
assert.equal(end.pitch, b.pitch);
assert.equal(end.bearing, b.bearing);
assert.deepEqual(cameraAt(p, {}, 1280, 720, 150), end, 'camera holds the end view');
retimeMapItem(p.shots[0], 30, 100);
assert.deepEqual(cameraAt(p, {}, 1280, 720, 130), end, 'retiming preserves the destination');
p.shots[0].animDur = 40;
assert.deepEqual(cameraAt(p, {}, 1280, 720, 70), end, 'animation duration controls camera completion independently of the bar');
assert.equal(p.shots[0].start, 30);
assert.equal(p.shots[0].dur, 100);
const invalid = JSON.parse(JSON.stringify(p)); invalid.shots[0].cameraTo.pitch = 100;
assert.throws(() => validateMapProject(invalid), /camera keyframe/);
delete invalid.shots[0].cameraTo;
assert.throws(() => validateMapProject(invalid), /camera keyframe/);

const object = { start: 10, dur: 100, moveStart: 20, moveEnd: 80 };
retimeMapItem(object, 30, 100);
assert.deepEqual(object, { start: 30, dur: 100, moveStart: 40, moveEnd: 100 });
retimeMapItem(object, 30, 15, false);
assert.deepEqual(object, { start: 30, dur: 15, moveStart: 40, moveEnd: 45 });
retimeMapItem(object, 44, 1, false);
assert.deepEqual(object, { start: 44, dur: 1, moveStart: 44, moveEnd: 45 });
console.log('Map camera keyframes and object retiming passed');
const timed = { start: 10, dur: 100, animDur: 60 };
setAnimationKey(timed, 'animationStart', 30);
setAnimationKey(timed, 'animationEnd', 80);
assert.equal(timed.start, 10, 'animation keys leave appearance time unchanged');
assert.equal(timed.dur, 100, 'animation keys leave disappearance time unchanged');
assert.equal(actionProgress(timed, 20), 0, 'hold initial state before animation starts');
assert.equal(actionProgress(timed, 55), .5);
assert.equal(actionProgress(timed, 95), 1, 'hold completed state until bar ends');
retimeMapItem(timed, 20, 100);
assert.equal(timed.animStart, 40);
assert.equal(timed.animEnd, 90);
retimeMapItem(timed, 20, 10, false);
assert.equal(timed.animStart, 29);
assert.equal(timed.animEnd, 30);
p.shots[0].animStart = 50; p.shots[0].animEnd = 90;
assert.deepEqual(cameraAt(p, {}, 1280, 720, 40), start, 'camera holds initial pose before animation key');
assert.deepEqual(cameraAt(p, {}, 1280, 720, 100), end, 'camera completes before shot bar ends');
validateMapProject(JSON.parse(JSON.stringify(p)));
