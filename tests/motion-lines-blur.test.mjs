import assert from 'node:assert/strict';
import { lineArtwork } from '../motion-lines.mjs';
import { cameraAt, layerBlur, makeCameraShot } from '../motion-camera.mjs';
import { validateProject } from '../engine.mjs';
const layers = ['back','subject','front'].map(id => ({id,name:id,type:'rect',x:200,y:200,w:100,h:100,scale:1,rotation:0,opacity:1,blur:0,in:0,out:119,keys:{}}));
const project = {version:1,width:800,height:600,fps:30,frames:120,bg:'#000000',layers};
const shot = {...makeCameraShot(project,'focus',0,'subject'),frontBlur:12,backBlur:32,endBehavior:'hold',trackFocus:false};
project.cameraShots = [shot];
const camera = cameraAt(project,100);
assert.equal(layerBlur(project,layers[0],camera),32);
assert.equal(layerBlur(project,layers[1],camera),0);
assert.equal(layerBlur(project,layers[2],camera),12);
shot.frontBlur=0;
assert.equal(layerBlur(project,layers[2],cameraAt(project,100)),0);
assert.equal(layerBlur(project,{...layers[1],blur:9},camera),9);
assert.ok(layerBlur(project,layers[0],cameraAt(project,15))<32,'blur fades in with the camera');
shot.endBehavior='return';
assert.equal(layerBlur(project,layers[0],cameraAt(project,100)),0,'blur ends with the clip');
delete shot.frontBlur;delete shot.backBlur;
shot.endBehavior='hold';
assert.ok(layerBlur(project,layers[0],cameraAt(project,100))>0,'saved legacy depth blur still works');
const art=lineArtwork([{x:10,y:20},{x:200,y:20},{x:220,y:80}]);
assert.equal(art.x-art.w/2+40,10);
assert.match(art.svgMarkup,/fill="none"/);
assert.equal(lineArtwork([{x:0,y:0}]),null);
project.layers.push({...layers[0],...art,type:'vector',id:'line'});
assert.equal(validateProject(JSON.parse(JSON.stringify(project))).layers.at(-1).isDrawnLine,true);
shot.frontBlur=81;
assert.throws(()=>validateProject(project),/camera blur/);
console.log('Drawn line project round trip and independent front/back camera blur passed');
